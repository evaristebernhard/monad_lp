import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:1440,height:1080}}),errors=[]
page.on('pageerror',e=>errors.push(e.message))
try{
await page.goto('http://127.0.0.1:5173/#selection')
await page.getByRole('heading',{name:'选池策略',exact:true}).waitFor()
assert.equal(await page.getByLabel('支付数量',{exact:true}).inputValue(),'0.1')
await page.waitForFunction(()=>Number(document.querySelector('output[aria-label="预计收到数量"]')?.textContent)>0,{},{timeout:90000})
const first=await page.getByTestId('selection-source-block').innerText()
await page.waitForFunction(initial=>document.querySelector('[data-testid="selection-source-block"]')?.textContent!==initial,first,{timeout:20000})
await page.getByRole('button',{name:'暂停',exact:true}).click()
await page.getByRole('button',{name:'链上核对',exact:true}).click()
await page.getByRole('status').filter({hasText:'核对通过'}).waitFor({timeout:90000})
console.log('14-pool live block advancement and real testnet quote selection matched')
await page.screenshot({path:'/tmp/pool-selection-live-desktop.png',fullPage:true})
await page.setViewportSize({width:390,height:844})
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
await page.screenshot({path:'/tmp/pool-selection-live-mobile.png',fullPage:true})
await page.setViewportSize({width:1440,height:1080})
await page.getByLabel('支付数量',{exact:true}).fill('0')
assert.equal(await page.getByLabel('预计收到数量',{exact:true}).innerText(),'—')
assert.equal(await page.getByRole('button',{name:'链上核对',exact:true}).isDisabled(),true)
await page.getByRole('button',{name:'刷新报价',exact:true}).click()
await page.getByRole('alert').waitFor()
await page.getByLabel('支付数量',{exact:true}).fill('0.2')
await page.waitForFunction(()=>Number(document.querySelector('output[aria-label="预计收到数量"]')?.textContent)>0,{},{timeout:90000})
await page.getByRole('button',{name:'暂停',exact:true}).click()
await page.getByLabel('切换兑换方向',{exact:true}).click()
assert.equal(await page.getByLabel('预计收到数量',{exact:true}).innerText(),'—')
await page.getByLabel('选择策略',{exact:true}).selectOption('dcar')
await page.getByRole('button',{name:'链上核对',exact:true}).click()
await page.getByRole('status').filter({hasText:'核对通过'}).waitFor({timeout:90000})
assert.equal(await page.getByLabel('输入数量 A').inputValue(),'0.1')
await page.getByLabel('输入数量 A').fill('0')
await page.getByRole('button',{name:'本地试跑',exact:true}).click()
await page.getByRole('alert').waitFor()
assert.deepEqual(errors,[])
console.log('DCAR replay, changed inputs/direction, validation, mobile layout and console passed')
}finally{await browser.close()}
