// Build-time only. The produced file needs Node.js, not npm or this repository.
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {execFileSync} from 'node:child_process'

const directory=path.dirname(fileURLToPath(import.meta.url))
const source=fs.readFileSync(path.join(directory,'buy.mjs'),'utf8')
const catalog=JSON.parse(fs.readFileSync(path.join(directory,'catalog.json'),'utf8'))
const old="const catalog=JSON.parse(fs.readFileSync(new URL('./catalog.json',import.meta.url),'utf8')).candidates"
if(!source.includes(old))throw Error('Entry changed: review catalog embedding before rebuilding')
const buildDirectory=path.resolve(directory,'../../output/standalone-build')
fs.mkdirSync(buildDirectory,{recursive:true})
const metafile=path.join(buildDirectory,'meta.json')
const destination=path.join(directory,'buy-standalone.mjs')
execFileSync('npx',['--yes','esbuild@0.25.0','--bundle','--platform=node','--format=esm','--target=node22',
 '--legal-comments=inline','--metafile='+metafile,'--outfile='+destination,'--sourcefile=standalone-entry.mjs'],
 {cwd:directory,input:source.replace(old,'const catalog='+JSON.stringify(catalog.candidates)),encoding:'utf8',stdio:['pipe','pipe','pipe']})
const metadata=JSON.parse(fs.readFileSync(metafile,'utf8'))
const outputs=Object.values(metadata.outputs)
if(outputs.length!==1)throw Error('Expected exactly one JavaScript file')
const imports=outputs[0].imports
if(imports.some(item=>!item.path.startsWith('node:')))throw Error('Unexpected runtime package dependencies: '+JSON.stringify(imports))
const packages=new Map()
for(const id of Object.keys(metadata.inputs)){
 let dir=path.dirname(path.resolve(directory,id))
 while(path.isAbsolute(dir)&&dir!==path.dirname(dir)){
  const manifest=path.join(dir,'package.json')
  if(fs.existsSync(manifest)){
   try{
    const metadata=JSON.parse(fs.readFileSync(manifest,'utf8'))
    if(metadata.name){
     const license=['LICENSE','LICENSE.md','LICENSE.txt','LICENCE','license','license.md'].map(name=>path.join(dir,name)).find(p=>fs.existsSync(p))
     if(license)packages.set(metadata.name+'@'+metadata.version,fs.readFileSync(license,'utf8'))
     break
    }
   }catch{}
  }
  dir=path.dirname(dir)
 }
}
const notices=[...packages].sort(([a],[b])=>a.localeCompare(b)).map(([name,license])=>name+'\n'+license).join('\n\n')
const banner='/* Monad best-buy standalone. Generated by build-standalone.mjs.\nCandidate routes and runtime libraries are embedded.\nDefault is PREVIEW; --send broadcasts one real mainnet transaction.\nThird-party licenses:\n'+notices.replaceAll('*/','* /')+'\n*/\n'
const code=fs.readFileSync(destination,'utf8')
fs.writeFileSync(destination,banner+"import {createRequire as standaloneCreateRequire} from 'node:module';\nconst require=standaloneCreateRequire(import.meta.url);\n"+code)
console.log(JSON.stringify({file:destination,bytes:fs.statSync(destination).size,candidates:catalog.candidates.length,imports,packages:[...packages.keys()]}))
